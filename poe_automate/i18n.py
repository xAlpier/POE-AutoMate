def get_text(language: str, key: str, *args: Any) -> str:
    lang_dict = TRANSLATIONS.get(language.upper(), TRANSLATIONS["TR"])
    text = lang_dict.get(key, TRANSLATIONS["EN"].get(key, key))
    if args:
        try:
            return text.format(*args)
        except Exception:
            return text
    return text
